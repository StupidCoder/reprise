Routine routine_at(unsigned bank, unsigned address) {
    const unsigned b = address < 0x8000 ? 0 : bank;
    for (const auto& e : entries) {
        if (e.bank == b && e.address == address) {
            return e.routine;
        }
    }
    return Routine::unknown;
}

