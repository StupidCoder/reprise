"""Turns the enhancement art in art/enhancements into C++ tables compiled into the game.

The game embeds its few pieces of original art, so it needs no image library
or texture files at run time. Run this after editing a PNG:

    python3 tools/embed_enhancement_art.py

water-droplet.png -> src/gamegear/water_droplet.hpp
    The 8x12 RGBA droplet of the water splashes (shared by the Game Gear
    games), embedded as-is.

mist-spray.png -> src/sonic1_gg/enhancements/mist_spray.hpp
    The waterfall mist: four spray curls of 1, 3, 5 and 7 pixels, each in its
    own 7x7 cell (left to right, aligned top-left). Opaque pixels are the bright
    core; translucent pixels the soft edge, which the game draws at 60% opacity.

Both are original art made for this project (the droplet with an image
generator, the mist curls drawn by hand), not graphics from the game.
"""
from pathlib import Path
from PIL import Image

root = Path(__file__).resolve().parents[1]
art = root / 'art' / 'enhancements'
out = root / 'src' / 'sonic1_gg' / 'enhancements'
shared = root / 'src' / 'gamegear'

droplet = Image.open(art / 'water-droplet.png').convert('RGBA')
assert droplet.size == (8, 12), droplet.size
colors = [f'{{{r},{g},{b},{a}}}' for r, g, b, a in droplet.getdata()]
(shared / 'water_droplet.hpp').write_text(
    '// Generated by tools/embed_enhancement_art.py from art/enhancements/water-droplet.png.\n'
    '#pragma once\n#include "platform/image.hpp"\n#include <array>\n\n'
    'namespace gg {\n'
    '// The 8x12 water droplet of the splash enhancement, row by row.\n'
    'inline constexpr std::array<platform::Color, 96> water_droplet{{\n' +
    ',\n'.join(','.join(colors[n:n + 8]) for n in range(0, 96, 8)) + '\n}};\n}\n')

mist = Image.open(art / 'mist-spray.png').convert('RGBA')
assert mist.size == (28, 7), mist.size
sizes = [1, 3, 5, 7]
sprites = []
for k, size in enumerate(sizes):
    rows = []
    for y in range(size):
        row = ''
        for x in range(size):
            alpha = mist.getpixel((k * 7 + x, y))[3]
            row += '2' if alpha >= 200 else '1' if alpha else '.'
        rows.append(f'"{row}"')
    sprites.append('{' + ', '.join(rows) + '}')
(out / 'mist_spray.hpp').write_text(
    '// Generated by tools/embed_enhancement_art.py from art/enhancements/mist-spray.png.\n'
    '#pragma once\n\nnamespace sonic1_gg {\n'
    '// Waterfall mist curls: 2 = bright core, 1 = soft edge, . = empty. Size 0 is a\n'
    '// dot, 1 a three-pixel comma, 2 a five-pixel curl and 3 a seven-pixel spiral.\n'
    'inline constexpr const char* spray_art[4][7] = {\n    ' + ',\n    '.join(sprites) + '};\n'
    'inline constexpr int spray_size[4] = {' + ', '.join(map(str, sizes)) + '};\n}\n')
print('Embedded water-droplet.png and mist-spray.png')
