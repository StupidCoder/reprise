app::ImportResult import_disk(std::span<const std::uint8_t> image) {
    if (!SensiDisk::has_directory(image)) {
        throw app::NotThisGame("This disk is not one of the Cannon Fodder disks.");
    }
    const SensiDisk disk(image);
    const int number = disk_number(disk);
    if (number == 0 || (number == 1 && disk.find("fodderc") == nullptr)) {
        throw app::NotThisGame("This Sensible Software disk is not one of the Cannon Fodder disks.");
    }
    app::ImportResult result;
    result.release = std::string(release_name);
    result.part = number;
    result.parts = disk_count;
    const auto disk_label = "disk " + std::to_string(number);
    for (const auto& file : files) {
        if (file.disk != number) {
            continue;
        }
        const auto* entry = disk.find(file.name);
        if (entry == nullptr) {
            throw std::runtime_error("Cannon Fodder " + disk_label + " lacks the file " + std::string(file.name) +
                                     "; this release is not supported yet.");
        }
        std::vector<std::uint8_t> bytes;
        bool good = false;
        if (auto stored = disk.read(*entry)) {
            try {
                bytes = is_rnc(*stored) ? unpack_rnc(*stored) : std::move(*stored);
                good = platform::sha256(bytes) == file.sha256;
            } catch (const std::exception&) {
                good = false;
            }
        }
        if (!good) {
            if (file.copy_on != 0) {
                continue; // the other disk's identical copy will be used
            }
            if (number == 1 && file.name == "fodderc") {
                throw std::runtime_error("This disk holds a different release of Cannon Fodder, which is not supported yet.");
            }
            throw std::runtime_error("The file " + std::string(file.name) + " on Cannon Fodder " + disk_label +
                                     " is damaged or from a different release.");
        }
        result.files.push_back({"disk" + std::to_string(number) + "/" + std::string(file.name), std::move(bytes)});
    }
    return result;
}

