bool Topaz9::pixel(unsigned char c, int x, int y) {
    if (x < 0 || x >= width || y < 0 || y >= height) {
        return false;
    }
    const std::size_t glyph = c >= 0x20 ? glyph_of[std::size_t(c - 0x20)] : glyph_of.back();
    return (glyphs[glyph][std::size_t(y)] >> (width - 1 - x) & 1) != 0;
}

