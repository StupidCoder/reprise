#!/usr/bin/env python3
"""Builds the screen effects' shaders (shared/ui/shaders/*.frag) into a C++ header of
SPIR-V (Vulkan) and MSL (Metal) for SDL's GPU renderer.

Needs glslangValidator and spirv-cross (for example `brew install glslang spirv-cross`).
The generated headers are committed, so building Reprise does not need these tools; run this
after changing a shader. DXIL (Direct3D 12) is not produced: there SDL picks Vulkan for the
GPU renderer, or another renderer, and the host filters on the CPU instead."""
import pathlib
import subprocess
import sys
import tempfile

ROOT = pathlib.Path(__file__).resolve().parent.parent
SHADERS = ROOT / 'shared' / 'ui' / 'shaders'


def byte_array(name, data):
    lines = [f'inline constexpr unsigned char {name}[] = {{']
    for i in range(0, len(data), 16):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in data[i:i + 16]) + ',')
    lines.append('};')
    return '\n'.join(lines)


def build(source):
    stem = source.stem
    with tempfile.TemporaryDirectory() as work:
        spv = pathlib.Path(work) / (stem + '.spv')
        msl = pathlib.Path(work) / (stem + '.msl')
        subprocess.run(['glslangValidator', '-V', '--target-env', 'vulkan1.0', '-S', 'frag',
                        '-o', str(spv), str(source)], check=True)
        subprocess.run(['spirv-cross', '--msl', '--msl-version', '20000', str(spv),
                        '--output', str(msl)], check=True)
        spirv_bytes = spv.read_bytes()
        msl_bytes = msl.read_bytes() + b'\0'
    header = SHADERS / (stem + '_frag.hpp')
    header.write_text(
        '// Generated by tools/build_shaders.py from ' + source.name + '; do not edit.\n'
        '#pragma once\n\n'
        'namespace ui::shaders {\n\n'
        f'// SPIR-V, entry point "main".\n{byte_array(stem + "_spirv", spirv_bytes)}\n\n'
        f'// Metal shading language source (NUL-terminated), entry point "main0".\n'
        f'{byte_array(stem + "_msl", msl_bytes)}\n\n'
        '} // namespace ui::shaders\n')
    print('wrote', header.relative_to(ROOT))


def main():
    sources = sorted(SHADERS.glob('*.frag'))
    if not sources:
        sys.exit('no shaders found')
    for source in sources:
        build(source)


if __name__ == '__main__':
    main()
