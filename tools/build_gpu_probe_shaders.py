#!/usr/bin/env python3
"""Generate the synthetic GPU host check's SPIR-V and Metal shaders. Requires glslangValidator
and spirv-cross; generated headers are committed, so normal builds need neither executable."""
from pathlib import Path
import subprocess
import tempfile

root = Path(__file__).resolve().parent / 'shaders'
text = '// Generated by tools/build_gpu_probe_shaders.py; synthetic validation shaders.\n'
text += '#pragma once\nnamespace probe_shaders {\n'
with tempfile.TemporaryDirectory() as work:
    for stage in ('vert', 'frag'):
        source = root / ('gpu_host_probe.' + stage)
        spv = Path(work) / (stage + '.spv')
        msl = Path(work) / (stage + '.msl')
        subprocess.run(['glslangValidator', '-V', str(source), '-o', str(spv)], check=True)
        subprocess.run(['spirv-cross', str(spv), '--msl', '--msl-version', '20000',
                        '--output', str(msl)], check=True)
        for suffix, data in (('spv', spv.read_bytes()), ('msl', msl.read_bytes() + b'\0')):
            text += 'inline constexpr unsigned char ' + stage + '_' + suffix + '[] = {\n'
            text += '\n'.join(','.join(str(x) for x in data[i:i+24]) + ','
                              for i in range(0, len(data), 24)) + '\n};\n'
text += '}\n'
(root / 'gpu_host_probe.hpp').write_text(text)
